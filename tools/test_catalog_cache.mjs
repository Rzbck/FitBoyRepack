import assert from 'node:assert/strict';
import {loadGameDetail,searchIndexMatchesCatalog} from '../site/assets/catalog-api.js';
globalThis.document={baseURI:'https://example.invalid/'};
const calls=new Map(), pending=new Map();
globalThis.fetch=async url=>{
  calls.set(url,(calls.get(url)||0)+1);
  if(pending.has(url))await pending.get(url);
  if(url.endsWith('/bad')&&calls.get(url)===1)return {ok:false,status:503};
  return {ok:true,json:async()=>({id:url,title:'Game'})};
};
const load=id=>loadGameDetail(id);
for(let i=0;i<24;i++)await load('g'+i);
await load('g0');await load('g24');await load('g0');await load('g1');
assert.equal(calls.get('https://example.invalid/g0'),1);
assert.equal(calls.get('https://example.invalid/g1'),2);
let release;
pending.set('https://example.invalid/slow',new Promise(r=>release=r));
const first=load('slow');
for(let i=30;i<60;i++)await load('g'+i);
const second=load('slow');
assert.equal(first,second);
release();await first;
assert.equal(calls.get('https://example.invalid/slow'),1);
await assert.rejects(load('bad'));await load('bad');
assert.equal(calls.get('https://example.invalid/bad'),2);
const catalog={count:2,generated_at:'a',metadata_generated_at:'b',steam_generated_at:'s'};
assert.equal(searchIndexMatchesCatalog({...catalog},catalog),true);
assert.equal(searchIndexMatchesCatalog({...catalog,generated_at:'c'},catalog),false);
assert.equal(searchIndexMatchesCatalog({...catalog,metadata_generated_at:'c'},catalog),false);
assert.equal(searchIndexMatchesCatalog({...catalog,steam_generated_at:'t'},catalog),false);
console.log('LRU, shared pending requests, retry and snapshot consistency OK');
